
CREATE TABLE RATES (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME_RATE VARCHAR_IGNORECASE
);

CREATE TABLE GENRE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR_IGNORECASE
);

CREATE TABLE USERS (
    ID LONG GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR_IGNORECASE,
    LOGIN VARCHAR_IGNORECASE,
    NAME VARCHAR_IGNORECASE,
    BIRTHDAY DATE
);

CREATE TABLE FILMS (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR,
    DESCRIPTION VARCHAR(200),
    RELEASE_DATE DATE,
    DURATION INTEGER,
    RATES INTEGER NOT NULL,
    CONSTRAINT FILMS_RATES_FK FOREIGN KEY (RATES) REFERENCES RATES(ID)
);

CREATE TABLE FILM_GENRE (
    FILM_ID INTEGER NOT NULL,
    GENRE_ID INTEGER NOT NULL,
    PRIMARY KEY (FILM_ID, GENRE_ID),
    CONSTRAINT FK_FILM_GENRE_FILM FOREIGN KEY (FILM_ID) REFERENCES FILMS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_FILM_GENRE_GENRE FOREIGN KEY (GENRE_ID) REFERENCES GENRE(ID) ON DELETE CASCADE
);

CREATE TABLE FILM_LIKES (
    FILM_ID LONG NOT NULL REFERENCES FILMS(ID) ON DELETE CASCADE,
    USER_ID LONG NOT NULL REFERENCES USERS(ID) ON DELETE CASCADE,
    PRIMARY KEY (FILM_ID, USER_ID)
);


CREATE TABLE FRIENDSHIP (
    USER_ID INTEGER REFERENCES USERS(ID) ON DELETE CASCADE,
    FRIEND_ID INTEGER REFERENCES USERS(ID) ON DELETE CASCADE,
    STATUS BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (USER_ID, FRIEND_ID)
);
